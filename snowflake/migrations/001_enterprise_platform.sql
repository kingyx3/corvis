CREATE OR REPLACE SECURE VIEW PM_SERVING.DOCUMENTS_V AS
SELECT
  D.TENANT_ID,
  D.DOCUMENT_ID,
  U.FILE_NAME,
  D.FUND_NAME,
  D.REPORT_PERIOD,
  D.DOCUMENT_TYPE,
  D.PAGE_COUNT,
  U.SIZE_BYTES,
  CASE
    WHEN U.SIZE_BYTES >= 1073741824 THEN TO_VARCHAR(ROUND(U.SIZE_BYTES / 1073741824, 1)) || ' GB'
    WHEN U.SIZE_BYTES >= 1048576 THEN TO_VARCHAR(ROUND(U.SIZE_BYTES / 1048576, 1)) || ' MB'
    ELSE TO_VARCHAR(ROUND(U.SIZE_BYTES / 1024, 1)) || ' KB'
  END AS SIZE_DISPLAY,
  CASE D.LOGICAL_STATUS
    WHEN 'PUBLISHED' THEN 'Published'
    WHEN 'REVIEW' THEN 'Review'
    WHEN 'EXTRACTING' THEN 'Extracting'
    WHEN 'QUEUED' THEN 'Queued'
    ELSE INITCAP(LOWER(D.LOGICAL_STATUS))
  END AS STATUS,
  D.PROGRESS_PERCENT,
  TO_VARCHAR(U.CREATED_AT, 'YYYY-MM-DD HH24:MI') AS UPLOADED_DISPLAY,
  U.CREATED_AT AS UPLOADED_AT,
  D.QUALITY,
  D.OBSERVATION_COUNT
FROM PM_SOURCE.DOCUMENT D
JOIN PM_SOURCE.DOCUMENT_UPLOAD U ON U.DOCUMENT_ID = D.DOCUMENT_ID AND U.TENANT_ID = D.TENANT_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY D.TENANT_ID, D.DOCUMENT_ID ORDER BY U.CREATED_AT DESC) = 1;

CREATE OR REPLACE SECURE VIEW PM_SERVING.OBSERVATIONS_V AS
SELECT
  O.TENANT_ID,
  O.OBSERVATION_ID,
  O.FUND_ID,
  O.FUND_NAME,
  O.COMPANY_ID,
  O.COMPANY_NAME,
  O.METRIC_CODE,
  O.METRIC_LABEL,
  O.NUMERIC_VALUE,
  COALESCE(O.CORRECTED_DISPLAY_VALUE, O.DISPLAY_VALUE) AS DISPLAY_VALUE,
  O.PERIOD_LABEL,
  O.PERIOD_END,
  O.DELTA_DISPLAY,
  O.CONFIDENCE_PERCENT,
  O.REVIEW_STATE,
  O.MATERIALITY,
  O.SOURCE_REFERENCE_ID,
  O.FUND_PERIOD_SNAPSHOT_ID,
  COALESCE(O.COMPANY_NAME, O.FUND_NAME, 'Source') || ' · ' || COALESCE(O.PERIOD_LABEL, '') AS SOURCE_LABEL
FROM PM_CANONICAL.OBSERVATION O;

CREATE OR REPLACE SECURE VIEW PM_SERVING.METRIC_FACTS_V AS
SELECT * FROM PM_SERVING.OBSERVATIONS_V WHERE REVIEW_STATE <> 'Rejected';

CREATE OR REPLACE SECURE VIEW PM_SERVING.FUND_PERIOD_SNAPSHOTS_V AS
SELECT TENANT_ID, FUND_PERIOD_SNAPSHOT_ID, FUND_ID, FUND_NAME, REPORT_PERIOD, VERSION, STATUS,
       HOLDINGS_COUNT, FACTS_COUNT, CREATED_AT, UPDATED_AT, PUBLISHED_AT
FROM PM_CURATED.FUND_PERIOD_SNAPSHOT;

CREATE OR REPLACE SECURE VIEW PM_SERVING.SOURCE_REFERENCES_V AS
SELECT R.TENANT_ID, R.SOURCE_REFERENCE_ID, R.DOCUMENT_ID, R.ARTIFACT_VERSION_ID, A.OBJECT_KEY,
       R.PAGE_NUMBER, R.PAGE_LABEL, R.BOUNDING_BOX, R.EXCERPT, R.SOURCE_DOCUMENT_ACCESS_ALLOWED
FROM PM_SOURCE.SOURCE_REFERENCE R
JOIN PM_SOURCE.DOCUMENT_ARTIFACT_VERSION A
  ON A.TENANT_ID = R.TENANT_ID AND A.ARTIFACT_VERSION_ID = R.ARTIFACT_VERSION_ID
WHERE A.DELETED_AT IS NULL;

CREATE OR REPLACE SECURE VIEW PM_SERVING.RECENT_ACTIVITY_V AS
SELECT TENANT_ID, ACTION, RESOURCE_TYPE, RESOURCE_ID, OUTCOME, OCCURRED_AT
FROM PM_CONTROL.AUDIT_EVENT;

