CREATE TABLE IF NOT EXISTS PM_CONTROL.ROLE_TENANT_ACCESS (
  ROLE_NAME STRING NOT NULL,
  TENANT_ID STRING NOT NULL,
  ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
  CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ROLE_NAME, TENANT_ID)
);

CREATE OR REPLACE ROW ACCESS POLICY PM_CONTROL.TENANT_ISOLATION AS (ROW_TENANT_ID STRING)
RETURNS BOOLEAN ->
  CURRENT_ROLE() = 'CORVIS_PLATFORM_SERVICE'
  OR EXISTS (
    SELECT 1
    FROM PM_CONTROL.ROLE_TENANT_ACCESS ACCESS_MAP
    WHERE ACCESS_MAP.ROLE_NAME = CURRENT_ROLE()
      AND ACCESS_MAP.TENANT_ID = ROW_TENANT_ID
      AND ACCESS_MAP.ACTIVE = TRUE
  );

