GRANT USAGE ON DATABASE CORVIS TO ROLE CORVIS_PLATFORM_SERVICE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CORVIS TO ROLE CORVIS_PLATFORM_SERVICE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN DATABASE CORVIS TO ROLE CORVIS_PLATFORM_SERVICE;
GRANT SELECT ON ALL VIEWS IN DATABASE CORVIS TO ROLE CORVIS_PLATFORM_SERVICE;
GRANT SELECT ON PM_CONTROL.ROLE_TENANT_ACCESS TO ROLE CORVIS_PLATFORM_SERVICE;
