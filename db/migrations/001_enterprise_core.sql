CREATE OR REPLACE SECURE VIEW PM_SERVING.OBSERVATIONS AS
SELECT TENANT_ID, OBSERVATION_ID, FUND_ID, COMPANY_ID, HOLDING_ID, INSTRUMENT_ID, METRIC_CODE,
       VALUE_NUMBER, VALUE_STRING, CURRENCY, ECONOMIC_PERIOD, REPORT_DATE, REVIEW_STATE,
       SOURCE_REFERENCE_ID, VERSION, UPDATED_AT
FROM PM_FACTS.OBSERVATION
WHERE REVIEW_STATE IN ('approved','review_required');

CREATE OR REPLACE SECURE VIEW PM_SERVING.FUND_PERIOD_SNAPSHOTS AS
SELECT TENANT_ID, SNAPSHOT_ID, FUND_ID, REPORT_PERIOD, VERSION, STATUS, FACT_IDS,
       BLOCKING_EXCEPTION_COUNT, SCHEMA_VERSION, TAXONOMY_VERSION, CREATED_AT, PUBLISHED_AT
FROM PM_CONSOLIDATED.FUND_PERIOD_SNAPSHOT;

