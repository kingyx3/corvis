CREATE TABLE IF NOT EXISTS PM_CONTROL.TENANT_ROLE_GRANT (
  TENANT_ID STRING NOT NULL,
  ROLE_NAME STRING NOT NULL,
  CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (TENANT_ID, ROLE_NAME)
);

CREATE OR REPLACE ROW ACCESS POLICY PM_CONTROL.TENANT_ISOLATION AS (ROW_TENANT_ID STRING)
RETURNS BOOLEAN ->
  EXISTS (
    SELECT 1 FROM PM_CONTROL.TENANT_ROLE_GRANT G
    WHERE G.TENANT_ID = ROW_TENANT_ID AND UPPER(G.ROLE_NAME) = UPPER(CURRENT_ROLE())
  );

